/* Builds data/elements.js from MMM-AtomVisualizer's data/elements.json, keeping only what
 * the atom simulation shows. Run once; the result is checked in.
 *
 *   git clone https://github.com/KristjanESPERANTO/MMM-AtomVisualizer /tmp/atomvis
 *   node tools/build-elements.js /tmp/atomvis/data/elements.json
 *
 * Sources: KristjanESPERANTO/MMM-AtomVisualizer (MIT), whose data comes from
 * Bowserinator/Periodic-Table-JSON (CC BY-SA 3.0).
 */
const fs = require("node:fs");
const path = require("node:path");

const src = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const rows = Object.entries(src)
	.sort(([, a], [, b]) => a.number - b.number)
	.map(([symbol, e]) => {
		const keep = {
			number: e.number,
			name: e.name,
			mass: e.atomicMass,
			category: e.category,
			phase: e.phase,
			shells: e.shells,
			configuration: e.electronConfiguration
		};
		return `\t\t${JSON.stringify(symbol)}: ${JSON.stringify(keep)}`;
	});

const out = `/* Properties of the 118 chemical elements, keyed by symbol. Generated by tools/build-elements.js
 * from KristjanESPERANTO/MMM-AtomVisualizer (MIT), data originally from
 * Bowserinator/Periodic-Table-JSON (CC BY-SA 3.0). Do not edit by hand.
 */
(function (root) {
	const ELEMENTS = {
${rows.join(",\n")}
	};

	root.ChaosElements = ELEMENTS;
	if (typeof module !== "undefined") module.exports = ELEMENTS;
})(typeof window !== "undefined" ? window : globalThis);
`;
fs.writeFileSync(path.join(__dirname, "..", "data", "elements.js"), out);
console.log(`wrote ${rows.length} elements`);
